let op='+';
let a=10;
let b=5;
switch(op){
    case '+':
        console.log(a+b);   
        break;
    case '-':
        console.log(a-b);       
        break;
    case '*':
        console.log(a*b);               
        break;
    case '/':
        console.log(a/b);   
        break;
    default:
        console.log('invalid operator');
        break;
}